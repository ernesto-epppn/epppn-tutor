import assert from "node:assert/strict";
import {pizzaMoneyMetrics} from "../app/pizzaCostMetrics";
const approx=(actual:number,expected:number)=>assert.ok(Math.abs(actual-expected)<1e-8,`${actual} !== ${expected}`);
assert.equal(pizzaMoneyMetrics({ingredientHt:4.44,packagingHt:null,sellingHt:0,recommendedHt:17,complete:false}),null,
  "Incomplete ingredient inputs must still block calculations");
const noPackagingEntered=pizzaMoneyMetrics({ingredientHt:4.44,packagingHt:null,sellingHt:0,recommendedHt:17,complete:true});
assert.ok(noPackagingEntered,"Blank packaging is optional when ingredients are complete");
approx(noPackagingEntered.packagingHt,0);
approx(noPackagingEntered.directCostHt,4.44);
approx(noPackagingEntered.grossMarginHt,17-4.44);
approx(noPackagingEntered.packagingPct,0);
approx(noPackagingEntered.directCostPct+noPackagingEntered.grossMarginPct,100);
const automatic=pizzaMoneyMetrics({ingredientHt:4.44,packagingHt:0.56,sellingHt:0,recommendedHt:17,complete:true});
assert.ok(automatic);
assert.equal(automatic.origin,"conseillé");
approx(automatic.saleHt,17);
approx(automatic.directCostHt,5);
approx(automatic.grossMarginHt,12);
approx(automatic.grossMarginPct,12/17*100);
approx(automatic.foodCostPct,4.44/17*100);
approx(automatic.packagingPct,0.56/17*100);
approx(automatic.directCostPct+automatic.grossMarginPct,100);
const manual=pizzaMoneyMetrics({ingredientHt:4.44,packagingHt:0.56,sellingHt:14,recommendedHt:17,complete:true});
assert.ok(manual);
assert.equal(manual.origin,"saisi");
approx(manual.grossMarginHt,9);
approx(manual.grossMarginPct,9/14*100);
const noPackaging=pizzaMoneyMetrics({ingredientHt:1.94,packagingHt:0,sellingHt:0,recommendedHt:12,complete:true});
assert.ok(noPackaging,"Explicit zero packaging and blank packaging are both valid");
approx(noPackaging.grossMarginHt,10.06);
const loss=pizzaMoneyMetrics({ingredientHt:4.44,packagingHt:0.56,sellingHt:3,recommendedHt:17,complete:true});
assert.ok(loss);
assert.equal(loss.isLoss,true);
approx(loss.grossMarginHt,-2);
assert.ok(loss.grossMarginPct<0,"Negative margins must not be shown as positive");
console.log("Pizza HT costing: optional packaging, recommended fallback, manual selling, percentages and loss OK");
