create table if not exists public.ernesto_manual_benchmark_cases (
  id bigint generated by default as identity primary key,
  title text,
  category text not null default 'Expert',
  question text not null,
  reference_answer text not null,
  required_points text[] not null default '{}'::text[],
  forbidden_points text[] not null default '{}'::text[],
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_run_at timestamptz,
  last_pass boolean,
  last_score integer,
  last_reference_score integer,
  last_reliability_score integer,
  last_result jsonb,
  mode text not null default 'ACTION'
);

alter table public.ernesto_manual_benchmark_cases enable row level security;

revoke all on table public.ernesto_manual_benchmark_cases from anon, authenticated;
grant all on table public.ernesto_manual_benchmark_cases to service_role;

create index if not exists ernesto_manual_benchmark_cases_active_idx
  on public.ernesto_manual_benchmark_cases(active, updated_at desc);

alter table public.ernesto_manual_benchmark_cases
  drop constraint if exists ernesto_manual_benchmark_cases_mode_check;

alter table public.ernesto_manual_benchmark_cases
  add constraint ernesto_manual_benchmark_cases_mode_check
  check (mode in ('ACTION','ANALYSE'));
